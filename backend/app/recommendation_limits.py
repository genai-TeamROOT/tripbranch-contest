"""추천 파이프라인과 Context 수집이 공유하는 후보 개수 정책."""

# 추천 결과와 후보 수집 요청에서 허용하는 최소 건수.
MIN_RECOMMENDATION_LIMIT = 1

# 추천 파이프라인이 한 번에 수집·보강하도록 허용하는 절대 후보 상한.
#
# 20에서 30으로 올렸다. 20이던 이유는 후보마다 TourAPI 상세 조회가 붙는다는
# 전제였는데(D-099 "채택하지 않은 것"), 추천 경로의 상세는 `PLACE_DETAILS_SOURCE`
# 기본값이 supabase가 되면서 후보 수와 무관하게 **배치 1회**가 됐다. 실측으로
# 후보 10곳과 30곳 모두 외부 호출 2회(목록 1 + places 배치 1)에 응답 시간도 같다.
#
# 30을 더 올리지 않는 이유는 그 이상이 필요한 근거가 아직 없어서다. 반경 2km
# 실측에서 30이면 밤 시간대까지 결과 5곳을 채운다(아래 주석 참고).
MAX_RECOMMENDATION_CANDIDATE_LIMIT = 30

# 사용자에게 최종 반환할 추천 장소의 기본 개수.
DEFAULT_RECOMMENDATION_RESULT_LIMIT = 5

# 점수 계산 전에 C가 수집할 추천 후보의 기본 개수.
#
# 노출 개수(RECOMMEND 5 / SCHEDULE 10)와의 차이가 여유분이다 — D가 영업 종료 후보를
# 하드 필터로 떨어뜨리므로(domain/scoring.py::_is_closed) 여유분이 없으면 카드가 다
# 안 채워진다.
#
# **10에서 30으로 올렸다.** 반경 2km 하드 필터 통과 수 실측(2026-08-31,
# scripts/measure_candidate_limit_impact.py). 괄호는 보충 조회 전이다:
#
#   중심점    한도   9시      14시     19시     21시     23시
#   안국역    10     6( 2)   16( 8)   12( 5)   12( 3)    6( 1)
#   안국역    30    26( 6)   52(26)   34(20)   36(12)   18( 6)
#   경복궁    10     7( 1)   14( 8)    9( 4)    5( 1)    1( 0)  <- 23시에 못 채움
#   경복궁    30    24( 7)   47(20)   32( 9)   34( 5)   16( 1)
#
# **보충 조회가 밤을 대부분 메운다.** 한도 10에서도 결과 5곳을 못 채우는 칸은
# 경복궁 23시 하나뿐이다. 그러니 "밤에 카드가 빈다"는 이 상향의 주된 근거가
# 아니다 — 보충을 빼고 보면 그렇게 보이지만(괄호 값), 실물은 보충이 돈다.
#
# 주된 근거는 **낮 시간대의 후보 폭**이다. 통과율이 100%인 시각에는 보충이 아예
# 돌지 않아(agent_runtime.py::_candidate_pool_exhausted) 후보가 이 값에서 끝난다.
# 가장 흔한 시간대의 선택지를 이 값 하나가 정하는 셈이다 — 10일 때 안국역 상위
# 5곳은 갤러리 미즈·뉘조·인사동 옥정이고, 넓히면 쌈지길·안녕인사동·북촌한옥마을이
# 올라온다. 통과 수는 후보 수에 거의 비례한다(멀어진다고 통과율이 떨어지지 않는다).
#
# 부수적으로 밤 보충 횟수도 준다 — 한 번에 더 많이 받으니 목표에 빨리 닿는다.
#
DEFAULT_RECOMMENDATION_CANDIDATE_LIMIT = 30
