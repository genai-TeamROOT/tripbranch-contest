-- Package B: 실행 Trace에 도메인 지표를 담을 자리. (TP-242)
--
-- **왜 필요한가.** trace_records의 컬럼은 step·prompt_version·scoring_version·
-- variant_id·latency_ms·token_usage·error_type뿐이고 자유 형식 필드가 없다. 그래서
-- "요청한 시간을 지켰는가", "보관함 장소가 어떤 사유로 몇 개 빠졌는가"처럼 기능
-- 품질을 세는 값을 담을 곳이 아무 데도 없었다. TP-238·TP-239가 시간 준수 판정과
-- 개수 상한을 만들었지만 둘 다 화면에만 쓰이고 기록되지 않아, 고치기 전후를 숫자로
-- 볼 방법이 없다.
--
-- **별도 테이블을 만들지 않는 이유.** run_id로 조인해야 하는 값이고 그 조인 지점이
-- 이미 trace_records다. 테이블을 새로 파면 같은 턴의 지연시간·버전과 품질 지표가
-- 서로 다른 곳에 흩어져, "이 프롬프트 버전에서 시간 준수율이 어땼나"를 물을 때마다
-- 두 테이블을 맞춰야 한다.
--
-- **jsonb인 이유.** 계약(llmops-trace-contract-v1.md 1절)이 "step 이름이나 버전 값의
-- 의미를 B는 판단하지 않고 호출자가 해석한 값을 그대로 저장한다"를 원칙으로 세워
-- 뒀다. 지표도 같은 성격이라 컬럼을 하나씩 늘리지 않는다 — 지표가 늘 때마다
-- 마이그레이션이 필요하면 세는 것을 미루게 된다.
--
-- **사용자 텍스트를 담지 않는다.** 장소 이름·발화는 이 저장소의 것이 아니다
-- (trace_records가 대화 삭제 때 안 지워지는 근거가 "사용자 텍스트가 없다"는 것이다).
-- 지표는 판정·개수·건수만 담고, 이름은 세는 쪽에서 길이만 취한다.
alter table public.trace_records
  add column if not exists metrics jsonb;

-- 기존 행은 null로 남는다. 지표를 안 실어 보내는 단계(llm_interpret·tool·scoring)도
-- 계속 null이다 — 빈 객체로 채우면 "지표가 없는 단계"와 "지표가 비어 있는 턴"을
-- 구분할 수 없다.

commit;
